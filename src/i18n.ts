export const dictionaries: Record<Lang, Dict> = { en, my }

export const LangContext = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({
  lang: 'en',
  t: en,
  setLang: () => {},
})

export function useLang() {
  return useContext(LangContext)
}

export function displayName(item: { nameEn: string; nameMy: string }, lang: Lang): string {
  return (lang === 'my' ? item.nameMy || item.nameEn : item.nameEn || item.nameMy) || '—'
}
